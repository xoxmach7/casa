-- 2. Квартиры этих ЖК: связная планировка секции и цена, посчитанная от площади.
--
--    Позиция на этаже берётся из номера (101 → 1, 102 → 2 …) — так планировки
--    совпадают по стояку, как в настоящем доме. Площадь задаётся комнатностью,
--    цена = площадь × цена за м² класса × этажный коэффициент (нижние этажи
--    дешевле), с округлением до десяти тысяч.
WITH demo AS (
  SELECT "id",
         CASE "class"
           WHEN 'Premium'  THEN 780000
           WHEN 'Business' THEN 560000
           ELSE 420000
         END AS ppm
  FROM "projects"
  WHERE "name" IN ('Алтын Орда', 'Есиль Парк', 'Сарыарқа Резиденс', 'Нұра Хиллс', 'Астана Тауэрс')
    AND "developer_name" = 'Кемел Құрылыс'
),
calc AS (
  SELECT a."id",
         d.ppm,
         a."floor",
         COALESCE(NULLIF(regexp_replace(a."number", '\D', '', 'g'), '')::int % 100, 1) AS unit
  FROM "apartments" a
  JOIN demo d ON d."id" = a."project_id"
),
shaped AS (
  SELECT "id",
         ppm,
         "floor",
         CASE unit WHEN 1 THEN 2 WHEN 2 THEN 1 WHEN 3 THEN 3 ELSE 2 END AS rooms,
         CASE unit
           WHEN 1 THEN 63.80
           WHEN 2 THEN 42.10
           WHEN 3 THEN 92.40
           ELSE 66.50
         END AS area
  FROM calc
)
UPDATE "apartments" a SET
  "rooms" = s.rooms,
  "area"  = s.area,
  "price" = round(s.area * s.ppm * (0.955 + 0.005 * LEAST(s."floor", 9)) / 10000) * 10000
FROM shaped s
WHERE a."id" = s."id";

