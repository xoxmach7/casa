/**
 * Легаси-скоринг `/api/scoring`.
 *
 * ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ. Модуль выдаёт то, что релиз 1.0 прямо запрещает:
 *  - ярлык кредитной истории GOOD / HAS_DELAYS / BAD
 *    (M03 Final Spec §14.2, §16.2, §21.3; CH-082 — «хорошая/плохая КИ»);
 *  - «вероятность одобрения» HIGH/MEDIUM/LOW (запрещённый вердикт);
 *  - оценку дохода из пенсионных взносов `estimateIncomeFromPension`
 *    (M04 §21/§22 REMOVE; прямое governance-решение заказчика 2026-08-25
 *    об откате формулы «ОПВ / 10% = доход»);
 *  - подбор программ (граница 1.1+, Bank Rules).
 *
 * Дополнительно классификатор КИ дефектен: список фраз-триггеров содержит
 * подстроку «просрочка», которая присутствует в ЛЮБОМ полном отчёте ПКБ как
 * подпись колонки, поэтому любой валидный отчёт получал минимум HAS_DELAYS.
 *
 * Включать только осознанно (например, для разбора легаси-данных):
 *   ENABLE_LEGACY_SCORING=true
 */
export function legacyScoringEnabled(): boolean {
  return process.env.ENABLE_LEGACY_SCORING === 'true';
}

/**
 * Жёсткое требование согласия на приём документов (М03/М04 §17).
 *
 * ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ намеренно: цель обработки пенсионных данных ещё не
 * утверждена (гейт RG-03), поэтому включение прямо сейчас заблокировало бы
 * ручной приём выписки ЕНПФ — основной рабочий путь релиза 1.0.
 *
 * Пока флаг выключен, согласие НЕ игнорируется молча: его фактический статус
 * вычисляется и пишется в аудит и в ответ (`consent_status`), чтобы пробел был
 * виден, а не спрятан. Включать сразу после утверждения целей обработки:
 *   ENFORCE_DOCUMENT_CONSENT=true
 */
export function documentConsentEnforced(): boolean {
  return process.env.ENFORCE_DOCUMENT_CONSENT === 'true';
}
