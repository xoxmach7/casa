/**
 * Отпечаток личности покупателя для дубль-чека и сверки при снятии объекта.
 *
 * Зачем не хранить телефон как есть: этот отпечаток лежит в фиксациях и в
 * записях о снятии объекта, куда смотрят и координатор, и админ, и он же
 * попадает в индексы. Прямое сравнение по телефону сделало бы базу фиксаций
 * базой телефонов покупателей всех агентств сразу.
 *
 * Канонический идентификатор — НОРМАЛИЗОВАННЫЙ ТЕЛЕФОН, а не ИИН. Причина
 * прозаическая: `Buyer.phone` обязателен, а ИИН покупателя на этапе показа
 * агент обычно ещё не знает. Если сравнивать по ИИН, дубль-чек пропустит
 * ровно те случаи, ради которых он существует.
 */

import crypto from 'crypto';

/**
 * Приводит казахстанский номер к 11 цифрам, начинающимся с 7.
 *
 * Один и тот же человек в двух CRM записан как +7 (777) 123-45-67, 8 777…
 * и 777… — без нормализации это три разных покупателя и три фиксации на
 * один объект.
 */
export function normalizePhone(raw: string): string {
  const digits = (raw || '').replace(/\D/g, '');
  if (digits.length === 11 && (digits.startsWith('8') || digits.startsWith('7'))) {
    return `7${digits.slice(1)}`;
  }
  if (digits.length === 10) return `7${digits}`;
  // Не наш формат — возвращаем как есть. Лучше не сматчить, чем сматчить
  // двух разных людей: ложный дубль отнимает у агента чужого клиента.
  return digits;
}

/**
 * Детерминированный отпечаток: HMAC-SHA256 от нормализованного телефона.
 *
 * Ключ обязателен и не короче 32 символов. Без ключа функция бросает, а не
 * переходит на голый SHA-256: пространство казахстанских номеров — меньше
 * 10^10, голый хэш перебирается на ноутбуке за минуты.
 */
export function buyerIdentityHash(
  phone: string,
  secret = process.env.MARKETPLACE_IDENTITY_HMAC_KEY || process.env.IIN_LOOKUP_HMAC_KEY,
): string {
  const normalized = normalizePhone(phone);
  if (!normalized) {
    throw new Error('Телефон покупателя пуст: отпечаток личности не может быть построен');
  }
  if (!secret || secret.length < 32) {
    throw new Error(
      'MARKETPLACE_IDENTITY_HMAC_KEY отсутствует или короче 32 символов: отпечаток личности не может быть построен',
    );
  }
  return crypto.createHmac('sha256', secret).update(normalized, 'utf8').digest('hex');
}

/** Маска телефона для показа человеку: последние 4 цифры. */
export function maskPhone(raw: string): string {
  const digits = normalizePhone(raw);
  if (digits.length < 4) return '•••••••';
  return `+7 ••• ••• ${digits.slice(-4)}`;
}
