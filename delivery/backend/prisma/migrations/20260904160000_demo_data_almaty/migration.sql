-- Цены пересчитываются под алматинский рынок: комфорт 620 тыс., бизнес 900 тыс.,
-- премиум 1,4 млн ₸ за м². Площадь и комнатность уже связны — их не трогаем.
WITH demo AS (
  SELECT "id",
         CASE "class"
           WHEN 'Premium'  THEN 1400000
           WHEN 'Business' THEN 900000
           ELSE 620000
         END AS ppm
  FROM "projects"
  WHERE "developer_name" = 'Кемел Құрылыс'
)
UPDATE "apartments" a SET
  "price" = round(a."area" * d.ppm * (0.955 + 0.005 * LEAST(a."floor", 9)) / 10000) * 10000
FROM demo d
WHERE d."id" = a."project_id";

