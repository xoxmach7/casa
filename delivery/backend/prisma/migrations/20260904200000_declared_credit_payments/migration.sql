-- Платежи по действующим кредитам со слов клиента.
--
-- Скоринг берёт их из отчёта ПКБ, и это правильно: подтверждённое число лучше
-- заявленного. Но пока отчёта нет, расчёт упирался в «Загрузите кредитную
-- историю» — даже когда у клиента кредитов нет вовсе. Брокер не мог за пять
-- минут довести клиента до ответа, а требовать PDF, которого не существует,
-- бессмысленно.
--
-- Теперь брокер может заявить сумму (или ноль — «кредитов нет»). Значение
-- помечается как DECLARED и НЕ выдаётся за подтверждённое: приоритет у ПКБ,
-- а в ответе скоринга такой прогон отмечен как «часть данных со слов клиента».
-- NULL означает «не спрашивали», а не ноль — инвариант модуля UNKNOWN ≠ 0.
ALTER TABLE "mortgage_client_profiles"
  ADD COLUMN IF NOT EXISTS "declared_credit_payments" DECIMAL(15,2);
