const NBSP = ' ';

// Короткие слова, которые нельзя оставлять в конце строки. Правило набора:
// предлоги, союзы и вообще любые слова в одну-две буквы «прилипают» к
// следующему слову, а тире не начинает строку.
const SHORT_WORD = '[А-Яа-яЁёA-Za-z]{1,2}|для|при|без|над|под|про|или|если|чтобы|как|что|уже';

// Слева от короткого слова — начало строки, обычный пробел, открывающая
// кавычка/скобка или уже проставленный неразрывный пробел (последнее нужно,
// чтобы второй проход добрал цепочку «и в одной»).
const BINDABLE = new RegExp(`(^|[ («„"${NBSP}])(${SHORT_WORD}) +`, 'g');

function bindOnce(text: string): string {
  return text.replace(BINDABLE, `$1$2${NBSP}`);
}

/**
 * Прибивает висячие союзы и предлоги к следующему слову и не даёт тире
 * начать строку. Одного прохода мало: он съедает пробел после короткого
 * слова, и следующее короткое слово подряд («и в одной») остаётся без
 * левой границы — поэтому проходов два.
 */
export function typo(text: string): string {
  return bindOnce(bindOnce(text)).replace(/ +—/g, `${NBSP}—`);
}
