/**
 * Релизные флаги ипотечных поверхностей.
 *
 * Релиз 1.0 — это канонический конвейер M01→M06. Всё, что показывает ипотечные
 * цифры мимо детерминированного движка M06 (локальные аннуитеты на Math.pow,
 * придуманные предельные доли платежа к доходу, вердикты банковских программ,
 * сценарии), относится к более поздним релизам: Bank Rules — 1.1, сценарии —
 * 1.2, клиентское заключение — 1.3.
 *
 * Такие экраны НЕ удаляются, а закрываются флагом: код и история остаются, но
 * пользователю в 1.0 не показываются. Значение по умолчанию — выключено, чтобы
 * включение было явным решением, а не следствием забытой переменной окружения.
 */

export function legacyMortgageToolsEnabled(): boolean {
  return process.env.NEXT_PUBLIC_MORTGAGE_LEGACY_TOOLS_ENABLED === "true";
}
